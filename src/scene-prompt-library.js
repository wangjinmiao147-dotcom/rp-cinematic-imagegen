    if (selected === 'fact') return `${core}\n事实阶段只提取原文已发生状态：连续动作、换场、否定、数量、衣着与局部照明各自核对；不从场景名称推断未写出的事件或身体状态。`;
    if (selected === 'relation') return `${core}\n关系阶段只核验已锁定瞬间：动作与接触归属、承重面、多人相对位置、画外及局部范围；观察方向、身体朝向、头部朝向和视线分别处理，机位不证明人物转身。未知左右或距离不补猜，不为解决冲突另造动作。`;
    return [core, '编辑阶段只用相关条目写简洁英文变化指令；未变身份、画风和通用结构由统一模板负责，不把本库全文写入生图提示词。',
        ...SCENE_PROMPT_REFERENCES.map(item => `${item.label}（${item.when}）：${item.guidance}`),
        '术语核对：' + PROMPT_TERM_REFERENCES.map(item => `${item.source}=${item.english}（${item.caution}）`).join('；'),
    ].join('\n');
